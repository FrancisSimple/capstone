"""## SECOND METHODS FOR IMPROVEMENT

# UPGRADED CELL 1:
Here, we build a single, elegant pipeline that handles augmentation, feature extraction, and classification.
"""

import tensorflow as tf
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout, RandomFlip, RandomRotation, RandomZoom
from tensorflow.keras.models import Sequential
from tensorflow.keras.callbacks import EarlyStopping

print(">>> Assembling Professional MobileNetV2 Architecture...")

# 1. Download the Pre-trained Brain
base_model = MobileNetV2(input_shape=(224, 224, 3), include_top=False, weights='imagenet')

# 2. FREEZE the brain for Phase 1
base_model.trainable = False

# 3. Build the unified Model
model = Sequential([
    # --- BLOCK 1: Data Augmentation (Only active during training) ---
    RandomFlip("horizontal_and_vertical", input_shape=(224, 224, 3)),
    RandomRotation(0.2), # Randomly rotate by 20%
    RandomZoom(0.2),     # Randomly zoom in/out

    # --- BLOCK 2: The Brain ---
    base_model,

    # --- BLOCK 3: The Decision Head ---
    GlobalAveragePooling2D(),
    Dropout(0.3), # Increased to 30% to force the model to learn harder
    Dense(1, activation='sigmoid')
])

# 4. Compile for Phase 1 (Standard learning rate)
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
    loss='binary_crossentropy',
    metrics=['accuracy']
)

# 5. Setup Early Stopping Guardrail
early_stop = EarlyStopping(
    monitor='val_loss',
    patience=4, # Give it 4 epochs of grace before stopping
    restore_best_weights=True
)

print("-" * 30)
print("SUCCESS: Architecture ready. Base model is frozen.")

"""# UPGRADED CELL 2
Now we train only the new layers we added. This allows the model to learn the basic difference between fresh and rotten without wrecking the foundational MobileNet logic.
"""

print(">>> PHASE 1: Warming up the custom head (Max 15 Epochs)...")

history_phase1 = model.fit(
    X, y,
    epochs=15,
    batch_size=32,
    validation_split=0.2,
    callbacks=[early_stop] # Will stop early if it maxes out its potential
)

print("-" * 30)
print("SUCCESS: Phase 1 Complete. The head is stabilized.")

"""# UPGRADED CELL 3:
Now that our custom head isn't making wild, random guesses, we carefully unfreeze the top layers of MobileNet and let it learn the specific textures of rotten fruit.
"""

print(">>> PHASE 2: Fine-tuning the core features...")

# 1. Unfreeze the base model
base_model.trainable = True

# 2. Re-freeze the bottom layers (we want to keep the basic edge/color detection)
# We only leave the top 30 layers trainable for fruit-specific features
for layer in base_model.layers[:-30]:
    layer.trainable = False

# 3. Re-compile with a MICRO learning rate (Crucial step!)
# 1e-5 ensures we only nudge the weights gently
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.00001),
    loss='binary_crossentropy',
    metrics=['accuracy']
)

# 4. Train again
history_phase2 = model.fit(
    X, y,
    epochs=20, # Give it time to slowly adjust
    batch_size=32,
    validation_split=0.2,
    callbacks=[early_stop]
)

print("-" * 30)
print("SUCCESS: Phase 2 Complete. Model is fully optimized.")
model.save('orange_quality_model_production.keras')
print("Model saved as 'orange_quality_model_production.keras'")

