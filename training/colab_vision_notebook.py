import numpy as np
import tensorflow as tf
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout
from tensorflow.keras.models import Model
from sklearn.utils import shuffle

# --- 1. MERGE THE DATASETS ---
print(">>> Merging Fresh and Rotten datasets...")
X = np.concatenate((X_rotten, X_fresh), axis=0)
y = np.concatenate((y_rotten, y_fresh), axis=0)

print(f"Total Images: {len(X)}")
print(f"Total Labels: {len(y)}")

# --- 2. SHUFFLE THE DECK ---
# We mix them up so the model doesn't memorize the order
print(">>> Shuffling data...")
X, y = shuffle(X, y, random_state=42)

# --- 3. BUILD THE MODEL ---
print(">>> Building MobileNetV2 Architecture...")

# Download the "Brain" of MobileNet (Pre-trained on ImageNet)
base_model = MobileNetV2(input_shape=(224, 224, 3),include_top=False,weights='imagenet')

# Freeze the brain (We only want to train the new decision layer)
base_model.trainable = False

# Add our Custom Classifier Head
x = base_model.output
x = GlobalAveragePooling2D()(x)
x = Dropout(0.2)(x)  # Regularization to prevent overfitting
# We use 'sigmoid' because we have a binary choice: 0 (Fresh) vs 1 (Rotten)
predictions = Dense(1, activation='sigmoid')(x)

model = Model(inputs=base_model.input, outputs=predictions)

# Compile the model
model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.0001),
              loss='binary_crossentropy', # Binary loss for 2 classes
              metrics=['accuracy'])

# --- 4. START TRAINING ---
print(">>> Starting Training (5 Epochs)...")

history = model.fit(
    X, y,
    epochs=5,           # 5 loops over the data
    batch_size=32,      # Process 32 images at a time
    validation_split=0.2 # Use 20% of data just for testing (not training)
)

print("-" * 30)
print("SUCCESS: Model is trained.")

# --- 5. SAVE THE MODEL ---
model.save('orange_quality_model.h5')
print("Model saved as 'orange_quality_model.h5'. You can download it from the files tab.")

