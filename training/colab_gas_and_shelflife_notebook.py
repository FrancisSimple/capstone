# CELL 7: Unsupervised Exploration - The Elbow Method
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler

print("🔍 Running the Elbow Method to find natural groupings...")

# 1. Select only our predictive features (ignore the sparse 'Shelf_Life_Days' target)
features = ['Vision_Quality', 'Area', 'Gas_Quality', 'Humidity', 'Temperature']
X_cluster = df_predict[features].copy()

# 2. Scale the data (CRITICAL for K-Means)
# We need Area (300,000) and Temperature (28.0) to have equal voting power
cluster_scaler = StandardScaler()
X_cluster_scaled = cluster_scaler.fit_transform(X_cluster)

# 3. Calculate WCSS (Within-Cluster Sum of Squares) for k = 1 to 10
wcss = []
k_range = range(1, 11)

for k in k_range:
    # init='k-means++' ensures smart initialization to avoid random traps
    kmeans = KMeans(n_clusters=k, init='k-means++', max_iter=300, n_init=10, random_state=42)
    kmeans.fit(X_cluster_scaled)
    wcss.append(kmeans.inertia_) # Inertia is the WCSS value

# 4. Plot the Elbow Graph
plt.figure(figsize=(10, 6))
plt.plot(k_range, wcss, marker='o', linestyle='-', color='#e74c3c', linewidth=2, markersize=8)
plt.title('Elbow Method: Finding the Optimal Number of Orange Phases', fontsize=16)
plt.xlabel('Number of Clusters (k)', fontsize=12)
plt.ylabel('WCSS (Within-Cluster Variance)', fontsize=12)
plt.xticks(k_range)
plt.grid(True, linestyle='--', alpha=0.7)

# We expect the elbow to be around 3 (Good, Medium, Spoilt), but the data might show 4 or 5!
plt.axvline(x=3, color='grey', linestyle='--', alpha=0.5, label='Original 3 Classes')
plt.legend()

plt.show()

