import joblib
import pandas as pd
import os
import matplotlib.pyplot as plt
import matplotlib.patches as patches

def predict_orange_quality(mq2, mq3, mq135, temp, hum):
    """
    Takes raw sensor readings, applies the required scaling and feature engineering,
    and returns the predicted orange quality with confidence percentages.
    """
    model_file = 'orange_quality_rf_model.pkl'
    scaler_file = 'orange_sensor_scaler.pkl'

    # 1. Check if the files exist
    if not os.path.exists(model_file) or not os.path.exists(scaler_file):
        return "❌ Error: Model or Scaler file not found. Please ensure the .pkl files are in the same folder."

    # 2. Load the trained model and the scaler
    model = joblib.load(model_file)
    scaler = joblib.load(scaler_file)

    # 3. Perform the EXACT same feature engineering from our training phase
    gas_sum = mq2 + mq3 + mq135
    mq3_ratio = mq3 / (gas_sum + 1e-6)
    temp_hum_index = temp * hum

    # 4. Create a DataFrame in the exact same column order as the training data
    feature_names = ['MQ2', 'MQ3', 'MQ135', 'Temperature', 'Humidity', 'Gas_Sum', 'MQ3_Ratio', 'Temp_Hum_Index']

    input_data = pd.DataFrame([[
        mq2, mq3, mq135, temp, hum, gas_sum, mq3_ratio, temp_hum_index
    ]], columns=feature_names)

    # 5. Scale the data using our loaded scaler
    scaled_data = scaler.transform(input_data)

    # 6. Calculate Overall Quality Percentage
    probabilities = model.predict_proba(scaled_data)[0]

    # We assign weights: Good = 100%, Medium = 50%, Spoilt = 0%
    prob_good = probabilities[0]
    prob_med = probabilities[1]
    prob_spoilt = probabilities[2]

    quality_score = (prob_good * 100) + (prob_med * 50) + (prob_spoilt * 0)

    # 7. Print Console Frame (Text-based)
    print("\n" + "╔" + "═"*46 + "╗")
    print("║" + " "*46 + "║")
    print("║" + " "*10 + "🍊 ORANGE QUALITY ANALYSIS 🍊" + " "*9 + "║")
    print("╠" + "═"*46 + "╣")
    print("║" + " "*46 + "║")
    print(f"║        OVERALL FRUIT HEALTH: {quality_score:>5.1f}%          ║")
    print("║" + " "*46 + "║")
    print("╚" + "═"*46 + "╝\n")

    # 8. Generate a Visual Diagram (Slide-ready image)
    fig, ax = plt.subplots(figsize=(8, 2))
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 1)
    ax.axis('off')

    # Background bar
    rect_bg = patches.Rectangle((0, 0.2), 100, 0.6, color='#e0e0e0', zorder=1)
    ax.add_patch(rect_bg)

    # Color logic based on score
    if quality_score >= 75:
        color = '#2ecc71' # Green
    elif quality_score >= 40:
        color = '#f1c40f' # Yellow
    else:
        color = '#e74c3c' # Red

    # Foreground quality bar
    rect_fg = patches.Rectangle((0, 0.2), quality_score, 0.6, color=color, zorder=2)
    ax.add_patch(rect_fg)

    # Add text over the bar
    plt.text(50, 0.5, f"{quality_score:.1f}% QUALITY",
             fontsize=20, fontweight='bold', ha='center', va='center', color='black', zorder=3)

    plt.title("Electronic Nose: Fruit Health Indicator", fontsize=14, color='gray', pad=15)
    plt.tight_layout()
    plt.show()

