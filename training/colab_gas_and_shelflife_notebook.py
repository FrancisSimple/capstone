# CELL 6: Data Fusion - Combining Gas, Vision, and Environment for Shelf Life Prediction
import pandas as pd
import numpy as np
import joblib

print("🔄 Fusing Data from Vision and Gas Models...")

# 1. Load our previously trained Gas Model and Scaler
gas_model = joblib.load('orange_quality_rf_model.pkl')
gas_scaler = joblib.load('orange_sensor_scaler.pkl')

# 2. Re-create the features so we can predict on the entire original dataset (df)
X_all = df[['MQ2', 'MQ3', 'MQ135', 'Temperature', 'Humidity']].copy()
X_all['Gas_Sum'] = X_all['MQ2'] + X_all['MQ3'] + X_all['MQ135']
X_all['MQ3_Ratio'] = X_all['MQ3'] / (X_all['Gas_Sum'] + 1e-6)
X_all['Temp_Hum_Index'] = X_all['Temperature'] * X_all['Humidity']

# 3. Calculate Gas Quality Percentages using predict_proba
X_all_scaled = gas_scaler.transform(X_all)
probs = gas_model.predict_proba(X_all_scaled)

# Weighted percentage: Good=100%, Medium=50%, Spoilt=0%
df['Gas_Quality'] = (probs[:, 0] * 100) + (probs[:, 1] * 50) + (probs[:, 2] * 0)

# 4. Synthesize matching Vision Data (to mirror your YOLO/MobileNet output)
# We add realistic noise so the ML model has to work to find the patterns
np.random.seed(42)

def generate_vision_data(row):
    if row['Quality'] == 'Good':
        vis_q = np.clip(np.random.normal(88, 8), 75, 100)
        area = int(np.random.normal(350000, 40000))
    elif row['Quality'] == 'Medium':
        vis_q = np.clip(np.random.normal(60, 12), 40, 74.9)
        area = int(np.random.normal(320000, 45000))
    else: # Spoilt
        vis_q = np.clip(np.random.normal(25, 10), 0, 39.9)
        area = int(np.random.normal(250000, 50000)) # Spoilt fruits tend to shrink
    return pd.Series([vis_q, area])

df[['Vision_Quality', 'Area']] = df.apply(generate_vision_data, axis=1)

# 5. Build the Final Prediction DataFrame
df_predict = df[['Vision_Quality', 'Area', 'Gas_Quality', 'Humidity', 'Temperature']].copy()

# 6. Create the Target Variable: Shelf Life (Days)
# Let's assume a perfect orange lasts 14 days. We blend Vision and Gas scores to determine the base life,
# then penalize for high temperatures and humidity.
base_life = (df_predict['Gas_Quality'] * 0.6 + df_predict['Vision_Quality'] * 0.4) / 100.0 * 14
env_penalty = ((df_predict['Temperature'] - 25) * 0.4) + ((df_predict['Humidity'] - 65) * 0.1)
df_predict['True_Shelf_Life'] = np.clip(base_life - env_penalty, 0.0, 14.0).round(1)

# 7. Setup the SEMI-SUPERVISED scenario
# We randomly "hide" the shelf-life labels for 90% of our data by replacing them with NaN.
df_predict['Shelf_Life_Days'] = df_predict['True_Shelf_Life']
mask = np.random.rand(len(df_predict)) > 0.10 # 90% True
df_predict.loc[mask, 'Shelf_Life_Days'] = np.nan

# Drop the "True" column so our model can't cheat
df_predict = df_predict.drop(columns=['True_Shelf_Life'])

print("✅ Data Fusion Complete!")
print("-" * 50)
print(f"Total Oranges in Dataset: {len(df_predict)}")
print(f"Oranges WITH known Shelf Life (Labeled): {df_predict['Shelf_Life_Days'].notna().sum()}")
print(f"Oranges WITHOUT known Shelf Life (Unlabeled): {df_predict['Shelf_Life_Days'].isna().sum()}")
print("-" * 50)
print("\nFirst 10 rows of the Master Dataset (Notice the NaNs in the target column!):")
